export const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { fr, ar };

export function translate(locale: Locale, key: MessageKey): string {
  return DICTIONARIES[locale]?.[key] ?? DICTIONARIES[DEFAULT_LOCALE][key] ?? key;
}

/** Interpolate {name} placeholders. */
export function translateVars(locale: Locale, key: MessageKey, vars: Record<string, string | number>): string {
  return translate(locale, key).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
